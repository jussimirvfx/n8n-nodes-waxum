const { readFileSync, writeFileSync } = require('node:fs');
const { runInNewContext } = require('node:vm');
const { resolve } = require('node:path');

const window = {};
const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/sync-catalog.cjs <path-to-English-playground.js>');
runInNewContext(readFileSync(source, 'utf8'), {window}, {timeout: 1000});
const groupMeta = window.__GROUP_META__;
const actions = window.__ENDPOINTS__.map(({group, key, label, method, path, fields, only, danger, raw_body}) => ({
  id: group + '/' + key, group, label, method, path: path.slice('/api/v1'.length),
  fields: group === 'fleet' && key === 'create'
    ? fields.map(field => field.name === 'reuse_on_conflict' ? {...field, name: 'reuse'} : field)
    : group === 'send' && key === 'buttons'
      ? fields.map(field => field.name === 'buttons'
        ? {...field, placeholder: '[{"button_id":"yes","display_text":"Yes"}]'}
        : field)
      : fields,
  channel: group === 'fleet' && key === 'create' ? 'web' : only || groupMeta[group].only,
  confirm: Boolean(danger || method === 'DELETE' || group === 'cloud-account' && key === 'connect'
    || (method !== 'GET' && ['fleet', 'tokens', 'nats'].includes(group))),
  rawBody: raw_body,
  download: ['info/export', 'cloud-media/download'].includes(group + '/' + key),
}));
const keys = new Set();
for (const action of actions) {
  const pathKeys = [...action.path.matchAll(/\{([^}]+)\}/g)].map(match => match[1]).filter(key => key !== 'sid');
  if (!['GET', 'POST', 'PUT', 'PATCH', 'DELETE'].includes(action.method) ||
      !action.path.startsWith('/') || action.path.includes('?') || keys.has(action.id) ||
      pathKeys.some(key => !action.fields.some(field => field.name === key && field.in_path))) {
    throw new Error('Invalid or duplicate operation: ' + action.id);
  }
  keys.add(action.id);
}
const categories = Object.fromEntries(Object.entries(groupMeta).map(([id, group]) => [id, group.title]));
const file = '// Generated by scripts/sync-catalog.cjs from the English Waxum console playground.\n' +
  "import type { CatalogAction } from './catalog-types';\n" +
  'export const categories: Record<string, string> = ' + JSON.stringify(categories, null, 2) + ';\n' +
  'export const actions: CatalogAction[] = ' + JSON.stringify(actions, null, 2) + ';\n';
writeFileSync(resolve(__dirname, '../nodes/Waxum/catalog.generated.ts'), file);
console.log(actions.length + ' operations, ' + Object.keys(categories).length + ' categories.');
